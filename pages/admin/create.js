document.addEventListener("DOMContentLoaded", () => {
  // 1. Initialize Quill Editor
  const quill = new Quill("#editor-container", {
    theme: "snow",
    placeholder: "Write the full article here...",
    modules: {
      toolbar: [
        [{ header: [2, 3, false] }], // Headings
        ["bold", "italic", "underline"], // Text formatting
        [{ list: "ordered" }, { list: "bullet" }], // Lists
        ["link"], // Links
        ["clean"], // Remove formatting button
      ],
    },
  });

  const form = document.getElementById("create-news-form");
  const messageDiv = document.getElementById("form-message");

  form.addEventListener("submit", async (e) => {
    e.preventDefault(); // Stop the page from reloading

    // 2. Extract HTML from Quill
    // quill.root.innerHTML gets the actual HTML tags generated by the editor
    const richTextContent = quill.root.innerHTML;

    // Basic validation: Prevent submitting empty editor ("<p><br></p>" is Quill's default empty state)
    if (richTextContent === "<p><br></p>") {
      alert("Please write some content before publishing.");
      return;
    }

    // 1. Gather data from the form
    const articleData = {
      title: document.getElementById("title").value,
      snippet: document.getElementById("snippet").value,
      content: document.getElementById("content").value,
      imageUrl: document.getElementById("imageUrl").value,
      imageCaption: document.getElementById("imageCaption").value,
      imageCredit: document.getElementById("imageCredit").value,
      authorId: document.getElementById("authorId").value, // Hardcoded for now
    };

    try {
      // 2. Send the POST request to the backend
      const response = await fetch("http://localhost:3000/api/news", {
        method: "POST",
        headers: {
          "Content-Type": "application/json", // Tells Express we are sending JSON
        },
        body: JSON.stringify(articleData),
      });

      const result = await response.json();

      if (response.ok) {
        // Success UI
        messageDiv.textContent =
          "Article published successfully! Redirecting...";
        messageDiv.className =
          "mt-4 p-4 rounded-lg text-sm font-bold bg-[#d7e2ff] text-[#021b3d] block";
        form.reset(); // Clear the form

        // Send them back to the dashboard after 2 seconds
        setTimeout(() => {
          window.location.href = "/";
        }, 2000);
      } else {
        throw new Error(result.error || "Failed to publish");
      }
    } catch (error) {
      console.error("Submit error:", error);
      messageDiv.textContent = `Error: ${error.message}`;
      messageDiv.className =
        "mt-4 p-4 rounded-lg text-sm font-bold bg-[#ffdad6] text-[#93000a] block";
    }
  });
});
